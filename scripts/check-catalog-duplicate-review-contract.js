'use strict';
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=f=>{try{return fs.readFileSync(path.join(root,f),'utf8')}catch(_){return''}};
let failed=0;const check=(n,o)=>o?console.log('PASS Duplicate Review:',n):(failed++,console.error('FAIL Duplicate Review:',n));
const db=read('database.js'),lib=read('lib/catalog-integrity.js'),route=read('routes/catalog-integrity.js'),ui=read('public/catalog-admin-workspace.js'),pkg=read('package.json');
check('durable duplicate review state exists',db.includes('catalog_duplicate_reviews'));
check('append-only duplicate review events exist',db.includes('catalog_duplicate_review_events'));
check('database blocks review event update and delete',db.includes('catalog_duplicate_review_events_no_update')&&db.includes('catalog_duplicate_review_events_no_delete'));
check('candidate fingerprint includes rule and exact products',lib.includes('duplicateCandidateKey'));
check('review authority exists',lib.includes('reviewDuplicateCandidate'));
check('review decisions are allowlisted',lib.includes('confirmed_duplicate')&&lib.includes('not_duplicate')&&lib.includes('needs_more_info'));
check('review requires meaningful reason',lib.includes('CATALOG_DUPLICATE_REVIEW_REASON_REQUIRED'));
check('review uses stale-state protection',lib.includes('CATALOG_DUPLICATE_REVIEW_STALE'));
check('not-duplicate review suppresses exact candidate',lib.includes("decision==='not_duplicate'"));
check('confirmed duplicate remains visible',lib.includes('Confirmed duplicate products need consolidation'));
check('API requires inventory authority',route.includes('/duplicate-review')&&route.includes("requirePermission('inventory')"));
check('UI exposes duplicate review actions',ui.includes('Not a duplicate')&&ui.includes('Confirm same item')&&ui.includes('Needs more info'));
check('UI never offers automatic merge',!ui.includes('Auto merge')&&!ui.includes('Merge automatically'));
check('syntax wall includes duplicate review contract',pkg.includes('check:catalog-duplicate-review'));
if(failed){console.error('Duplicate Review contract failed: '+failed);process.exit(1)}console.log('Duplicate Review contract passed.');
