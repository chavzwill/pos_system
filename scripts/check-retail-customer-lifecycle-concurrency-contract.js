'use strict';
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const lock=read('lib/lifecycleLock.js');
const checkout=read('routes/retail-checkout-hardening.js');
const returns=read('routes/retail-return-hardening.js');
const accounts=read('routes/customer-account-integrity.js');
const drawers=read('routes/drawer-session-hardening.js');
const checks=[];
const check=(name,pass)=>checks.push({name,pass:!!pass});
check('lifecycle locks are database-backed',lock.includes('CREATE TABLE IF NOT EXISTS lifecycle_operation_locks')&&lock.includes('resource_key TEXT PRIMARY KEY'));
check('lifecycle locks have bounded stale recovery',lock.includes("datetime('now','-' || ? || ' seconds')")&&lock.includes('ttlSeconds'));
check('ambiguous disconnect does not eagerly unlock',lock.includes("res.once('finish',release)")&&!lock.includes("res.once('close',release)"));
check('lock contention fails closed with retry guidance',lock.includes("code:'lifecycle_operation_busy'")&&lock.includes("Retry-After"));
check('customer checkout is serialized',checkout.includes('customer-commerce:')&&checkout.includes("label:'customer checkout'"));
check('checkout rejects negative cash-back input',checkout.includes('Cash-back amount cannot be negative'));
check('checkout validates cash-back against authoritative reward state',checkout.includes('Cash-back redemption exceeds the customer')&&checkout.includes('cash_back_type_active'));
check('checkout binds downstream cash-back to authoritative value',checkout.includes('body.cash_back_applied=authoritativeCashBack'));
check('cash tender uses net total after credits and rewards',checkout.includes('netTotal')&&checkout.includes('Cash tendered cannot be less than the sale total'));
check('split tender uses authoritative net total',checkout.includes('Split tender amounts')&&checkout.includes('authoritative sale total'));
check('return lifecycle serializes original transaction',returns.includes('retail-return:')&&returns.includes("label:'return or customer-account operation'"));
check('credit-affecting returns serialize customer account',returns.includes('customer-commerce:'));
check('account payments serialize against checkout and returns',accounts.includes('customer-commerce:')&&accounts.includes("label:'customer account operation'"));
check('explicit account allocations cannot omit part of payment',accounts.includes('must exactly match the payment amount'));
check('duplicate invoice allocations are rejected',accounts.includes('allocated more than once'));
check('drawer opening serializes drawer and cashier',drawers.includes('cash-drawer:')&&drawers.includes('cashier-drawer:'));
check('drawer close and reconciliation serialize session',drawers.includes('drawer-session:')&&drawers.includes("label:'cash drawer reconciliation'"));
check('cashier cannot silently switch to another open drawer',drawers.includes('already have')&&drawers.includes('Close or reconcile that session before opening a different drawer'));
for(const c of checks)console.log(`${c.pass?'PASS':'FAIL'} Retail lifecycle: ${c.name}`);
if(checks.some(c=>!c.pass))process.exit(1);
console.log(`Retail/customer lifecycle concurrency contract OK (${checks.length} checks).`);
