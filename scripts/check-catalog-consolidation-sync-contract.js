'use strict';
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
let failed=0;
const check=(n,o)=>o?console.log('PASS Consolidation Sync:',n):(failed++,console.error('FAIL Consolidation Sync:',n));
const route=read('routes/commerce-sync.js'),pkg=read('package.json');
check('commerce contract version includes consolidation payload',/CONTRACT_VERSION = '2026-09-20\.[123]'/.test(route));
check('catalog export includes product consolidations',route.includes('product_consolidations'));
check('mapping exports duplicate and survivor ids',route.includes('duplicate_product_id')&&route.includes('survivor_product_id'));
check('mapping exports duplicate and survivor skus',route.includes('duplicate_sku')&&route.includes('survivor_sku'));
check('mapping exports consolidation timestamp',route.includes('consolidated_at'));
check('catalog export joins survivor identity',route.includes('consolidated_into_product_id')&&route.includes('consolidated_into_sku'));
check('availability resolves canonical product',route.includes('resolveCanonicalAvailability'));
check('availability response exposes requested sku',route.includes('requested_sku'));
check('availability response exposes canonicalized flag',route.includes('canonicalized'));
check('availability never returns inactive survivor',route.includes('CANONICAL_PRODUCT_NOT_ACTIVE'));
check('availability safe failure code exists',route.includes('COMMERCE_SYNC_AVAILABILITY_UNAVAILABLE'));
check('inventory changes safe failure code exists',route.includes('COMMERCE_SYNC_INVENTORY_CHANGES_UNAVAILABLE'));
check('catalog mapping excludes internal reason and employee identity',!route.includes('consolidated_by')&&!route.includes('review_version'));
check('syntax wall includes consolidation sync contract',pkg.includes('check:catalog-consolidation-sync'));
if(failed){console.error('Consolidation Sync contract failed: '+failed);process.exit(1)}console.log('Consolidation Sync contract passed.');
