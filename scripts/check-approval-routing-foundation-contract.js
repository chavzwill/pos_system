'use strict';
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=(p)=>fs.existsSync(path.join(root,p))?fs.readFileSync(path.join(root,p),'utf8'):'';
const lib=read('lib/approval-routing.js');
const route=read('routes/approval-routing.js');
const admin=read('routes/department-approval-admin.js');
const errors=read('lib/approval-routing-errors.js');
const ui=read('public/department-approvals-ui.js');
const guide=read('public/department-approvals-guide-me.js');
const deferred=read('public/shell-deferred.js');
const mount=read('routes/employee-end-shift-assistant.js');
const checks=[];
checks.push(['normalized departments exist',lib.includes('CREATE TABLE IF NOT EXISTS departments')]);
checks.push(['manager membership is explicit',lib.includes('employee_department_memberships')&&lib.includes('is_manager')]);
checks.push(['approval envelopes are durable',lib.includes('approval_requests')&&lib.includes('approval_events')]);
checks.push(['events are append only',lib.includes('approval_events')&&!lib.includes('UPDATE approval_events')]);
checks.push(['manager authority checks branch and membership',lib.includes('isAuthorizedDepartmentManager')&&lib.includes('branch_id')]);
checks.push(['concurrent external replay handles storage contention',lib.includes('waitForExternalReplay')&&lib.includes('isStorageBusy')]);
checks.push(['decision actor comes from session',route.includes('req.employee.id')&&!route.includes('approved_by = req.body')]);
checks.push(['API keys cannot decide',route.includes('APPROVAL_API_KEY_FORBIDDEN')]);
checks.push(['department administration is security controlled',admin.includes("requirePermission('security_assign')")]);
checks.push(['approval routes are mounted',mount.includes("require('./approval-routing')")]);
checks.push(['manager queue uses human language',ui.includes('My Department Approvals')&&ui.includes('Waiting for')]);
checks.push(['Guide Me exposes approval review and setup tasks',guide.includes("REVIEW_TITLE='Review department approvals'")&&guide.includes("SETUP_TITLE='Set up approval departments'" )]);
checks.push(['approval Guide Me handles queue review and authoritative-module boundary',guide.includes('Review the oldest waiting request')&&guide.includes('owning module')&&guide.includes('security-assignment authority')]);
checks.push(['Guide Me never performs final decisions',guide.includes('will not approve or reject anything on your behalf')]);
checks.push(['shell deferred-loads approval UI and Guide Me',deferred.includes("'/department-approvals-ui.js'")&&deferred.includes("'/department-approvals-guide-me.js'" )]);
checks.push(['approval routes use centralized safe error responder',route.includes('sendApprovalError')&&admin.includes('sendApprovalError')]);
checks.push(['approval error layer exposes stable codes without raw database errors',errors.includes('APPROVAL_INTERNAL_ERROR')&&errors.includes('DEPARTMENT_CODE_CONFLICT')&&errors.includes('safeApprovalError')]);
checks.push(['approval routes do not return raw exception messages',!route.includes('json({error:e.message')&&!admin.includes('json({error:e.message')]);
checks.push(['approval UI consumes stable error codes',ui.includes('error.code')&&ui.includes('friendlyError')&&ui.includes('retryable')]);
let failed=0;
for(const [name,ok] of checks){if(ok)console.log(`PASS Approval routing: ${name}`);else{console.error(`FAIL Approval routing: ${name}`);failed++;}}
if(failed)process.exit(1);
console.log(`Approval routing foundation contract OK (${checks.length} checks).`);
