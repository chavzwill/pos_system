'use strict';
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=f=>{try{return fs.readFileSync(path.join(root,f),'utf8')}catch(_){return''}};
let failed=0;
const check=(n,o)=>o?console.log('PASS Catalog Queue:',n):(failed++,console.error('FAIL Catalog Queue:',n));
const lib=read('lib/catalog-integrity.js'),ui=read('public/catalog-admin-workspace.js'),pkg=read('package.json');
check('catalog authority builds remediation queue',lib.includes('buildRemediationQueue'));
check('queue groups issues by exact record identity',lib.includes('recordKey'));
check('queue preserves raw issue evidence',lib.includes('issues:[]')&&lib.includes('group.issues.push(item)'));
check('queue priority derives from severity',lib.includes('SEVERITY_ORDER'));
check('queue sorting is deterministic',lib.includes('localeCompare'));
check('queue exposes priority counts',lib.includes('by_severity'));
check('queue is read-only coordination',!lib.includes('auto_fix_catalog')&&!lib.includes('autoMerge'));
check('UI labels remediation queue in staff language',ui.includes('Work queue'));
check('UI supports priority filter',ui.includes('data-health-severity'));
check('UI supports issue filter',ui.includes('data-health-issue'));
check('UI supports queue search',ui.includes('data-health-search'));
check('UI provides Work next action',ui.includes('Work next'));
check('UI can open exact queue product',ui.includes('data-queue-product'));
check('UI never offers automatic merge',!ui.includes('Auto merge')&&!ui.includes('Merge automatically'));
check('full syntax wall includes remediation queue contract',pkg.includes('check:catalog-remediation-queue'));
if(failed){console.error('Catalog Queue contract failed: '+failed);process.exit(1)}console.log('Catalog Queue contract passed.');
