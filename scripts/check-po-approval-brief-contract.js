'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const {buildApprovalNotes,extractApprovalNotes,withApprovalBrief}=require('../lib/purchase-order-approval-notes');
const purpose='Restock the branch after a confirmed shortage';
const requested_for='Montego Bay branch / retail customers';
const stored=buildApprovalNotes({approval_purpose:purpose,requested_for,notes:'Deliver before Friday'});
assert.equal(stored,'Reason for purchase: '+purpose+'\nRequested for: '+requested_for+'\nAdditional notes: Deliver before Friday');
assert.deepEqual(extractApprovalNotes(stored),{approval_purpose:purpose,requested_for,additional_notes:'Deliver before Friday'});
assert.equal(withApprovalBrief({id:1,notes:stored}).requested_for,requested_for);
assert.equal(buildApprovalNotes({notes:'Legacy purchase order notes'}),'Legacy purchase order notes');
assert.equal(extractApprovalNotes('Legacy purchase order notes').additional_notes,'Legacy purchase order notes');
assert.throws(()=>buildApprovalNotes({approval_purpose:'restock'}),/who or what/i);
assert.throws(()=>buildApprovalNotes({requested_for:'customer'}),/why/i);
assert.throws(()=>buildApprovalNotes({approval_purpose:'x'.repeat(601),requested_for:'Branch'}),/length/);
assert.equal(buildApprovalNotes({approval_purpose:'Service\nreplacement',requested_for:'Field\tteam'}).includes('\nRequested for: Field team'),true);
assert.match(buildApprovalNotes({approval_purpose:purpose,requested_for,source_notes:'Approved PR notes'}),/Source purchase request notes: Approved PR notes/);
const ui=read('public/purchasing-workspace.js');
const po=read('routes/purchase-orders.js');
const pr=read('routes/purchase-requests.js');
const css=read('public/purchasing-workspace.css');
assert.match(ui,/name="approval_purpose" required/);
assert.match(ui,/name="requested_for" required/);
assert.match(ui,/tt-purch-convert-purpose/);
assert.match(ui,/tt-purch-convert-for/);
assert.match(ui,/approvalBrief\(x\)}<section class="tt-purch__items"/);
assert.match(po,/storedNotes = buildApprovalNotes/);
assert.match(po,/res\.json\(withApprovalBrief\(po\)\)/);
assert.match(pr,/source_notes: pr\.notes/);
assert.match(css,/\.tt-purch__approval-brief dl/);
console.log('PASS PO approval justification: purpose, beneficiary, validation, legacy orders, PR conversion, approver presentation');
