'use strict';
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checkout=read('routes/retail-checkout-hardening.js');
const promotions=read('routes/promotions.js');
const checks=[];const check=(name,pass)=>checks.push({name,pass:!!pass});
check('promotion redemption is serialized by code',checkout.includes('promotion-code:')&&checkout.includes("customer checkout or promotion redemption"));
check('checkout revalidates promotion from database',checkout.includes('validatePromotionAtCheckout')&&checkout.includes('JOIN promotions p ON p.id=pc.promotion_id'));
check('promotion scope uses authoritative catalog/category lines',checkout.includes('authoritativeLines')&&checkout.includes('category_id: product.category_id'));
check('promotion minimum purchase uses authoritative subtotal',checkout.includes('minimum merchandise subtotal')&&checkout.includes('authoritativeSubtotal'));
check('stale client discount is rejected',checkout.includes('Promotion pricing changed. Expected discount'));
check('usage limit is checked at checkout',checkout.includes('Promotion code has reached its usage limit'));
check('promotion name/code are rebound to database values',checkout.includes('body.promotion_code = String(promo.code)')&&checkout.includes('body.promotion_name = promo.name'));
check('completed transaction atomically increments code usage',checkout.includes('CREATE TRIGGER IF NOT EXISTS trg_transaction_promotion_usage')&&checkout.includes("NEW.status='completed'"));
check('legacy use-code endpoint cannot increment usage separately',promotions.includes('accounted_at_checkout:true')&&!/router\.post\('\/use-code'[\s\S]*times_used\s*=\s*times_used\s*\+\s*1/.test(promotions));
check('promotion percentage is bounded',promotions.includes('Percentage promotions cannot exceed 100%'));
check('promotion dates are ordered',promotions.includes('Promotion end date cannot be before its start date'));
check('promotion usage limit is positive integer',promotions.includes('Usage limit must be a positive whole number'));
for(const c of checks)console.log(`${c.pass?'PASS':'FAIL'} Retail promotion: ${c.name}`);
if(checks.some(c=>!c.pass))process.exit(1);
console.log(`Retail promotion integrity contract OK (${checks.length} checks).`);
